#!/usr/bin/env node
/*
 * generate-search-index — the data behind the searchable app catalogue on
 * GitHub Pages (web/search/).
 *
 * SAMPLES.md answers "is there a port that shows X" for a reader who scrolls.
 * It cannot answer the question this repository is actually asked, which is
 * the other way round and has two halves:
 *
 *   "my system runs UI5 1.84 — which of these 430 ports will render on it?"
 *   "which ports use sap.m.Table at all, not just the one filed under it?"
 *
 * Neither is answerable from the sidecars. A port's `entity` is the ONE
 * control the demo kit sample is about, and a port that merely *uses* a Table
 * inside a page about something else is invisible to it; and the UI5 release
 * a port needs is written nowhere — the POST_171 deviations name it in prose
 * ("exists only since UI5 1.77"), which is a sentence for a human, not a
 * filter.
 *
 * Both come out of @abap2ui5/linter, which already reconstructs the view a
 * builder chain produces and resolves every control and member against the
 * UI5 metadata snapshot — the same pass view-gates runs. Here it is asked for
 * two things it computes anyway:
 *
 *   stats.types            every control the port BUILDS, with occurrences
 *   `*-too-new` findings   every control/member/aggregation/enum value/icon
 *                          newer than the 1.71 floor, each carrying `since`
 *
 * The highest of those `since` values IS the port's minimum UI5 release, and
 * the floor itself when there are none. That is the same number view-gates
 * gates on and the sidecars declare in prose, derived rather than restated,
 * so the page cannot drift from the corpus.
 *
 * The render gate is deliberately off: it needs a browser and answers a
 * different question (does the view load), and this pass runs on every Pages
 * deploy.
 *
 * NOT committed — written into web/search/, which is a build output like
 * web/build/. It is regenerated by `deploy-web` on every deploy, so it is
 * never staler than the site serving it, and a port PR does not carry a
 * 200 KB diff of derived data.
 *
 *   node scripts/generate-search-index.mjs            write web/search/apps.json
 *   node scripts/generate-search-index.mjs --out X    write it elsewhere
 *   node scripts/generate-search-index.mjs --quiet    no per-port progress
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { checkAbapSource } from '@abap2ui5/linter';
import { readDescript } from './lib/descript.mjs';
import { isSkippedDir } from './lib/src-tree.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const argOut = process.argv.indexOf('--out');
const OUT = argOut === -1
  ? path.join(ROOT, 'web', 'search', 'apps.json')
  : path.resolve(process.argv[argOut + 1]);
/* Progress is a carriage-returned counter, which is a live line on a terminal
 * and 431 concatenated lines in a CI log. Off unless someone is watching. */
const QUIET = process.argv.includes('--quiet') || !process.stdout.isTTY;

/** The floor view-gates holds every port to — and the answer for a port that
 *  needs nothing newer. Keep it in step with view-gates.mjs MIN_UI5. */
const MIN_UI5 = '1.71';

/** The repository the source links point into. The Pages site is built from
 *  main, so that is the ref the links follow. */
const REPO = 'abap2UI5/samples-controls';
const REF = 'main';

/** Where a class can be opened and run without a system. `?src=` takes a raw
 *  GitHub URL (playground src/shell/deep-link.mjs ALLOWED_HOSTS). */
const PLAYGROUND = 'https://abap2ui5.github.io/playground/';

/* What the playground's bundled OpenUI5 actually carries
 * (playground tools/build-ui5.mjs UI5_LIBRARIES). A library that is not in
 * that build is a control that will not render there, so a port using one
 * gets no playground link rather than a link to a blank frame. The version is
 * what that build pins — a port needing a release above it would not render
 * either, and the page says so. */
const PLAYGROUND_LIBS = new Set([
  'sap.ui.core', 'sap.m', 'sap.f', 'sap.ui.layout',
  'sap.ui.table', 'sap.ui.unified', 'sap.tnt', 'sap.uxap',
]);
const PLAYGROUND_UI5 = '1.151';

/* Every UI5 library a control in this corpus can come from. A control name is
 * mapped to its library by LONGEST prefix, because the namespace is not the
 * library: sap.ui.layout.form.SimpleForm ships in sap.ui.layout, and
 * sap.ui.model.type.Date in sap.ui.core. The OpenUI5 ones are read from
 * ui5/universe.json so a new library in the snapshot needs no edit here; the
 * SAPUI5-only ones (src/03) are listed, because no snapshot in this
 * repository covers them. */
const universe = JSON.parse(fs.readFileSync(path.join(ROOT, 'ui5', 'universe.json'), 'utf8'));
const EXTRA_LIBS = [
  /* SAPUI5-only — the src/03 collection */
  'sap.ui.comp', 'sap.suite.ui.commons', 'sap.suite.ui.microchart',
  'sap.ui.vk', 'sap.ui.vbm', 'sap.viz', 'sap.gantt', 'sap.ndc',
  'sap.ushell', 'sap.collaboration', 'sap.ui.generic',
  /* OpenUI5 libraries no sample in ui5/universe.json is filed under */
  'sap.ui.webc.main', 'sap.ui.webc.fiori',
];
const KNOWN_LIBS = [...new Set([...universe.libs.map((l) => l.lib), ...EXTRA_LIBS])]
  .sort((a, b) => b.length - a.length);

/** The library a control ships in.
 *
 *  Longest known prefix wins, because the namespace is not the library. The
 *  fallback matters as much as the match: everything under `sap.ui.` that is
 *  not a library of its own SHIPS IN sap.ui.core — `sap.ui.model.type.Date`
 *  and `sap.ui.base.Object` have no library called `sap.ui.model` or
 *  `sap.ui.base` behind them, and offering one as a filter would invite a
 *  reader to look for a library that does not exist.
 */
const libraryOf = (control) => KNOWN_LIBS.find((lib) => control === lib || control.startsWith(`${lib}.`))
  || (control.startsWith('sap.ui.') ? 'sap.ui.core' : control.split('.').slice(0, -1).join('.'));

/* The library facet for a class with no sidecar — the SAPUI5 collection under
 * src/03, whose controls no snapshot in this repository resolves. Its DESCRIPT
 * names the library itself ("sap.suite.ui.commons - Timeline"), which is the
 * answer; the fallback drops sap.ui.core and sap.m, because every view builds
 * something from both and neither is what the port is about. */
function descriptLibrary(descript, libs) {
  const head = descript.split(' - ')[0].trim();
  if (KNOWN_LIBS.includes(head)) return head;
  return libs.find((l) => l !== 'sap.ui.core' && l !== 'sap.m') || libs[0] || '';
}

/** Compare two dotted UI5 versions numerically ("1.9" < "1.71" < "1.120"). */
function cmpVersion(a, b) {
  const pa = String(a).split('.').map(Number);
  const pb = String(b).split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d;
  }
  return 0;
}

/** "1.77.0" / "1.77" -> "1.77" — the minor is what a system is called by. */
const shortVersion = (v) => String(v).split('.').slice(0, 2).join('.');

const walk = (dir, out = []) => {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (isSkippedDir(name)) continue;
    if (fs.statSync(full).isDirectory()) walk(full, out);
    else if (full.endsWith('.clas.abap')) out.push(full);
  }
  return out;
};

const descriptions = JSON.parse(fs.readFileSync(path.join(ROOT, 'ui5', 'descriptions.json'), 'utf8'));
const demokit = descriptions.demokit || {};

/* ---------------------------------------------------------------- collect */

const files = walk(path.join(ROOT, 'src'));
const controlIds = new Map();          // control name -> index in `controls`
const idOf = (name) => {
  if (!controlIds.has(name)) controlIds.set(name, controlIds.size);
  return controlIds.get(name);
};

/* The in-system overview app is not a sample. It implements z2ui5_if_app like
 * every port, so the walk finds it, but it rebuilds no demo kit original — it
 * is the table that LISTS them, this page's own counterpart inside a system.
 * Left in, it answered every second query: it builds 25 control types, so it
 * matched sap.m.Table, SearchField and half the corpus' controls, and being
 * app_000 it sorted to the top of all of them. The catalogue links it from the
 * footer, where a reader looking for the overview will look. */
const OVERVIEW = 'z2ui5_cl_smpc_app_000';

const apps = [];
let failed = 0;

for (const file of files) {
  const source = fs.readFileSync(file, 'utf8');
  if (!/INTERFACES\s+z2ui5_if_app\s*\./i.test(source)) continue;

  const cls = path.basename(file, '.clas.abap');
  if (cls === OVERVIEW) continue;
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  const metaPath = path.join(ROOT, 'meta', `${cls}.json`);
  const meta = fs.existsSync(metaPath) ? JSON.parse(fs.readFileSync(metaPath, 'utf8')) : null;

  const descript = readDescript(file);
  const docu = meta?.sample ? demokit[meta.sample] : null;

  /* The linter pass. A class it cannot reconstruct is still catalogued — it
   * keeps its sidecar facts and loses only the derived ones, which is better
   * than dropping a port out of the catalogue over a parse. */
  let types = {};
  let tooNew = [];
  let usesBuilder = false;
  let note = null;
  try {
    const r = checkAbapSource(source, { minUi5: MIN_UI5, render: false, file: rel });
    usesBuilder = !!r.usesBuilder;
    types = r.stats?.types || {};
    tooNew = r.findings
      .filter((f) => /-too-new$/.test(f.type) && f.since)
      .map((f) => ({
        type: f.type,
        name: [f.control, f.member, f.value].filter(Boolean).join('.') || f.type,
        since: shortVersion(f.since),
      }));
  } catch (err) {
    failed++;
    note = `linter: ${err.message}`;
  }

  /* The port's minimum UI5 release: the highest `since` the linter reported
   * above the floor, and the floor itself when it reported none. */
  const minUi5 = tooNew.reduce(
    (acc, f) => (cmpVersion(f.since, acc) > 0 ? f.since : acc),
    MIN_UI5,
  );

  const controls = Object.keys(types).sort();
  const libs = [...new Set(controls.map(libraryOf))].sort();
  const sapui5Only = !meta && cls.includes('_sapui5_');

  /* Only a port whose libraries the playground build carries, and whose floor
   * that build's UI5 reaches, gets a "run it" link. `z2ui5.cc.*` is not a UI5
 * library at all — those are abap2UI5's own custom controls, shipped with the
 * framework's frontend, so they are there wherever abap2UI5 is. */
  const runnable = usesBuilder
    && !sapui5Only
    && libs.length > 0
    && libs.every((l) => PLAYGROUND_LIBS.has(l) || l.startsWith('z2ui5.'))
    && cmpVersion(minUi5, PLAYGROUND_UI5) <= 0;

  apps.push({
    class: cls,
    file: rel,
    /* The demo kit's own name for the sample — "Action List Item". 18 ports
     * have no demokit entry, and the SAPUI5 collection has no sidecar at all;
     * those fall back to the WHOLE DESCRIPT rather than its first half,
     * because the half before the dash is the entity ("sap.m.ActionListItem",
     * "sap.suite.ui.microchart") and a card headed by a library name says
     * nothing about which sample it is. */
    title: docu?.name || descript,
    summary: (source.match(/^" @summary (.+?)\r?$/m) || [, ''])[1].trim(),
    keywords: (source.match(/^" @keywords (.+?)\r?$/m) || [, ''])[1].trim(),
    /* The demo kit paragraph — the longest piece of real prose about the
     * sample, and the reason a free-text search finds a port by what it does
     * rather than only by what it is called. Tags stripped: a few carry
     * <code> markup. */
    description: (docu?.description || '').replace(/<[^>]+>/g, '').trim(),
    sample: meta?.sample || '',
    entity: meta?.entity || '',
    library: meta?.entity ? libraryOf(meta.entity) : descriptLibrary(descript, libs),
    libraries: libs,
    status: meta?.status || (sapui5Only ? 'collection' : ''),
    deviations: [...new Set((meta?.deviations || []).map((d) => d.type))].sort(),
    minUi5,
    /* What made it that release — the tooltip behind the badge, so a filter
     * result can be argued with rather than only believed. */
    needs: tooNew.sort((a, b) => cmpVersion(b.since, a.since) || a.name.localeCompare(b.name)),
    controls: controls.map(idOf),
    controlCount: Object.values(types).reduce((a, b) => a + b, 0),
    sapui5Only,
    runnable,
    ...(note ? { note } : {}),
  });

  if (!QUIET) process.stdout.write(`\rgenerate-search-index: ${apps.length} ports`);
}

if (!QUIET) process.stdout.write('\n');

/* ------------------------------------------------------------------ write */

const controls = [...controlIds.keys()];
const releases = [...new Set(apps.map((a) => a.minUi5))].sort(cmpVersion);

const index = {
  note: 'Generated by scripts/generate-search-index.mjs — a build output, not committed. Do not hand-edit.',
  repo: REPO,
  ref: REF,
  source: `https://github.com/${REPO}/blob/${REF}/`,
  raw: `https://raw.githubusercontent.com/${REPO}/${REF}/`,
  playground: PLAYGROUND,
  playgroundUi5: PLAYGROUND_UI5,
  playgroundLibraries: [...PLAYGROUND_LIBS].sort(),
  minUi5: MIN_UI5,
  ui5Snapshot: universe.release,
  releases,
  /* One dictionary, referenced by index from every port: the same 400-odd
   * control names would otherwise be repeated 430 times. */
  controls,
  apps: apps.sort((a, b) => a.class.localeCompare(b.class)),
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `${JSON.stringify(index)}\n`);

const rel = path.relative(ROOT, OUT).split(path.sep).join('/');
const size = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log(
  `generate-search-index: ${apps.length} ports, ${controls.length} controls, `
  + `releases ${releases[0]}–${releases[releases.length - 1]}, `
  + `${apps.filter((a) => a.runnable).length} runnable in the playground `
  + `-> ${rel} (${size} KB)`,
);
if (failed) console.log(`generate-search-index: ${failed} port(s) the linter could not reconstruct — catalogued without derived facts`);
